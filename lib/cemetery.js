// The Cemetery — localStorage graveyard + Markdown report formatting.

const PREFIX = 'deadlink:tomb:';

function store() {
  try {
    if (typeof localStorage !== 'undefined') return localStorage;
  } catch { /* private mode etc. */ }
  return null;
}

function keyFor(url) { return PREFIX + url; }

/** Save a tombstone. Tombstone: { url, verdict, lastSeen, snapshotUrl, checkedAt } */
export function saveTombstone(tomb) {
  const s = store();
  if (!s) return false;
  try {
    s.setItem(keyFor(tomb.url), JSON.stringify({ ...tomb, checkedAt: tomb.checkedAt || new Date().toISOString() }));
    return true;
  } catch { return false; }
}

export function loadTombstones() {
  const s = store();
  if (!s) return [];
  const out = [];
  for (let i = 0; i < s.length; i++) {
    const k = s.key(i);
    if (k && k.startsWith(PREFIX)) {
      try { out.push(JSON.parse(s.getItem(k))); } catch { /* skip corrupt */ }
    }
  }
  return out.sort((a, b) => (b.checkedAt || '').localeCompare(a.checkedAt || ''));
}

export function clearCemetery() {
  const s = store();
  if (!s) return 0;
  let n = 0;
  const keys = [];
  for (let i = 0; i < s.length; i++) {
    const k = s.key(i);
    if (k && k.startsWith(PREFIX)) keys.push(k);
  }
  keys.forEach((k) => { s.removeItem(k); n++; });
  return n;
}

/** Copyable Markdown link-rot report. rows: [{url, verdict, snapshotUrl}] */
export function formatMarkdownReport(rows, title = 'Deadlink report') {
  const counts = { alive: 0, dead: 0, unknown: 0, 'no-snapshot': 0 };
  for (const r of rows) counts[r.verdict] = (counts[r.verdict] || 0) + 1;
  const lines = [
    `# ${title}`,
    '',
    `Checked ${rows.length} links — ${counts.alive} alive, ${counts.dead} dead, ${counts.unknown} unknown.`,
    '',
    '| Link | Verdict | Resurrection |',
    '| ---- | ------- | ------------ |',
  ];
  for (const r of rows) {
    const rez = r.snapshotUrl ? `[archived copy](${r.snapshotUrl})` : '—';
    lines.push(`| ${r.url} | ${r.verdict} | ${rez} |`);
  }
  lines.push('', '_Generated by Deadlink — the web forgets, we remember._');
  return lines.join('\n');
}
